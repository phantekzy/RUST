// COMMON COLLECTIONS
// Updating a Vector
// To create a vector then add elements to it , we can use the push method :
// Main function
fn main() {
    let mut v = Vec::new();
    // Using the push method to add values to a vector
    v.push(5);
    v.push(6);
    v.push(9);
    v.push(1);
    // Print to screen
    println!("{:?}", v);
}
